func setupPackageModule(t *testing.T) {
	t.Helper()
	t.Chdir(t.TempDir())
	t.Setenv("GOENV", "off")
	t.Setenv("GOFLAGS", "")
	t.Setenv("GOWORK", "off")
	t.Setenv("GOTOOLCHAIN", "local")
	t.Setenv("GOOS", "linux")
	t.Setenv("GOARCH", "amd64")
	t.Setenv("CGO_ENABLED", "0")
	writeFile(t, "go.mod", "module example.com/fixture\n\ngo 1.24\n")
}

func TestPackageBuildConstraints(t *testing.T) {
	setupPackageModule(t)
	for name, source := range map[string]string{
		"base.go":           "package fixture\nimport _ \"example.invalid/not-installed\"\ntype Base int",
		"target_linux.go":   "package fixture\ntype Linux int",
		"target_windows.go": "package fixture\ntype Windows int",
		"cpu_amd64.go":      "package fixture\ntype AMD64 int",
		"cpu_arm64.go":      "package fixture\ntype ARM64 int",
		"feature.go":        "//go:build feature && !blocked\n\npackage fixture\ntype Feature int",
		"legacy.go":         "// +build legacy\n\npackage fixture\ntype Legacy int",
		"cgo.go":            "package fixture\nimport \"C\"\ntype Cgo int",
	} {
		writeFile(t, name, source)
	}
	for _, tt := range []struct {
		name, goos, goarch, cgo, goflags string
		args, want                       []string
	}{
		{
			name: "linux", goos: "linux", goarch: "amd64", cgo: "0",
			want: []string{"base.go", "cpu_amd64.go", "target_linux.go"},
		},
		{
			name: "windows arm64", goos: "windows", goarch: "arm64", cgo: "0",
			want: []string{"base.go", "cpu_arm64.go", "target_windows.go"},
		},
		{
			name: "tags and cgo", goos: "linux", goarch: "amd64", cgo: "1",
			args: []string{"--tags=feature,legacy"},
			want: []string{"base.go", "cgo.go", "cpu_amd64.go", "feature.go", "legacy.go", "target_linux.go"},
		},
		{
			name: "inherited flags", goos: "linux", goarch: "amd64", cgo: "0", goflags: "-tags=feature",
			want: []string{"base.go", "cpu_amd64.go", "feature.go", "target_linux.go"},
		},
		{
			name: "explicit tags override flags", goos: "linux", goarch: "amd64", cgo: "0", goflags: "-tags=feature",
			args: []string{"--tags=feature,blocked"},
			want: []string{"base.go", "cpu_amd64.go", "target_linux.go"},
		},
		{
			name: "empty tags override flags", goos: "linux", goarch: "amd64", cgo: "0", goflags: "-tags=feature",
			args: []string{"--tags="},
			want: []string{"base.go", "cpu_amd64.go", "target_linux.go"},
		},
	} {
		t.Run(tt.name, func(t *testing.T) {
			t.Setenv("GOOS", tt.goos)
			t.Setenv("GOARCH", tt.goarch)
			t.Setenv("CGO_ENABLED", tt.cgo)
			t.Setenv("GOFLAGS", tt.goflags)
			r, code, stderr := runJSON(t, append([]string{"--packages", "--types"}, tt.args...)...)
			if code != 0 || r.Status != "complete" || !reflect.DeepEqual(declarationFiles(r), tt.want) {
				t.Fatalf("code=%d files=%v stderr=%s report=%+v", code, declarationFiles(r), stderr, r)
			}
		})
	}
}

func TestPackageDiscoverySelection(t *testing.T) {
	setupPackageModule(t)
	t.Setenv("GIT_CONFIG_GLOBAL", os.DevNull)
	t.Setenv("GIT_CONFIG_NOSYSTEM", "1")
	git(t, "init", "-q")
	for name, source := range map[string]string{
		".gitignore":             "ignored.go\n",
		"base.go":                "package fixture\ntype Base int",
		"ignored.go":             "package fixture\ntype Ignored int",
		"generated.go":           "// Code generated by test. DO NOT EDIT.\npackage fixture\ntype Generated int",
		"base_test.go":           "package fixture\ntype InternalTest int",
		"external_test.go":       "package fixture_test\ntype ExternalTest int",
		"target_windows_test.go": "package fixture\ntype WindowsTest int",
		"sub/child.go":           "package sub\ntype Child int",
		"nested/go.mod":          "module example.com/nested\n\ngo 1.24\n",
		"nested/other.go":        "package nested\ntype Other int",
	} {
		writeFile(t, name, source)
	}
	for _, tt := range []struct {
		name       string
		args, want []string
	}{
		{"default package", nil, []string{"base.go", "ignored.go"}},
		{"recursive", []string{"./..."}, []string{"base.go", "ignored.go", "sub/child.go"}},
		{"tests and exclusions", []string{"./...", "--include-tests", "--exclude=sub/**", "--exclude=ignored.go"},
			[]string{"base.go", "base_test.go", "external_test.go"}},
		{"overlapping patterns", []string{".", "./...", "example.com/fixture/sub"},
			[]string{"base.go", "ignored.go", "sub/child.go"}},
	} {
		t.Run(tt.name, func(t *testing.T) {
			r, code, stderr := runJSON(t, append([]string{"--packages", "--types"}, tt.args...)...)
			if code != 0 || !reflect.DeepEqual(declarationFiles(r), tt.want) ||
				r.Summary.SkippedReasons["generated"] != 1 {
				t.Fatalf("code=%d files=%v stderr=%s report=%+v", code, declarationFiles(r), stderr, r)
			}
		})
	}
	r, code, _ := runJSON(t, ".", "--types")
	if code != 0 || !strings.Contains(strings.Join(declarationFiles(r), ","), "nested/other.go") ||
		strings.Contains(strings.Join(declarationFiles(r), ","), "ignored.go") {
		t.Fatalf("default discovery changed: code=%d files=%v", code, declarationFiles(r))
	}
}

func TestPackageDiscoveryCrossPackageComparison(t *testing.T) {
	setupPackageModule(t)
	writeFile(t, "base.go", "package fixture\nfunc First(x int) int { return x + 1 }")
	writeFile(t, "sub/child.go", "package sub\nfunc Second(y int) int { return y + 1 }")
	r, code, stderr := runJSON(t, "--packages", "./...", "--min-tokens=0", "--threshold=1")
	if code != 0 || r.Summary.Functions != 2 || len(r.Pairs) != 1 {
		t.Fatalf("cross-package matches lost: code=%d stderr=%s report=%+v", code, stderr, r)
	}
}

func TestPackageDiscoveryFailures(t *testing.T) {
	setupPackageModule(t)
	writeFile(t, "base.go", "package fixture\ntype Base int")
	writeFile(t, "target_windows.go", "package fixture\ntype Windows int")
	t.Run("bad package preserves valid results", func(t *testing.T) {
		r, code, stderr := runJSON(t, "--packages", ".", "./missing", "--types")
		if code != 2 || r.Status != "incomplete" || !strings.Contains(stderr, "missing") ||
			!reflect.DeepEqual(declarationFiles(r), []string{"base.go"}) {
			t.Fatalf("code=%d stderr=%s report=%+v", code, stderr, r)
		}
	})
	t.Run("unmatched pattern warns without fallback", func(t *testing.T) {
		writeFile(t, "empty/.keep", "")
		r, code, stderr := runJSON(t, "--packages", "./empty/...", "--types")
		if code != 0 || r.Status != "complete" || r.Summary.Files != 0 ||
			!strings.Contains(stderr, "matched no packages") {
			t.Fatalf("code=%d stderr=%s report=%+v", code, stderr, r)
		}
	})
	t.Run("no fallback without go", func(t *testing.T) {
		t.Setenv("PATH", t.TempDir())
		r, code, stderr := runJSON(t, "--packages", ".", "--types")
		if code != 2 || r.Status != "incomplete" || r.Summary.Files != 0 ||
			!strings.Contains(stderr, "go list failed") {
			t.Fatalf("code=%d stderr=%s report=%+v", code, stderr, r)
		}
	})
}

func TestPackageDiscoverySymlink(t *testing.T) {
	setupPackageModule(t)
	writeFile(t, "base.go", "package fixture\ntype Base int")
	if err := os.Symlink("base.go", "link.go"); err != nil {
		t.Skip("symlinks unavailable:", err)
	}
	r, code, stderr := runJSON(t, "--packages", "--types")
	if code != 0 || !reflect.DeepEqual(declarationFiles(r), []string{"base.go"}) ||
		r.Summary.SkippedReasons["symlink"] != 1 {
		t.Fatalf("code=%d stderr=%s report=%+v", code, stderr, r)
	}
}

func TestPackagePathsEndingInGo(t *testing.T) {
	setupPackageModule(t)
	writeFile(t, "component.go/source.go", "package component\ntype Component int")
	writeFile(t, "target_windows.go", "package fixture\ntype Windows int")
	for _, pattern := range []string{"./component.go", "example.com/fixture/component.go"} {
		t.Run(pattern, func(t *testing.T) {
			r, code, stderr := runJSON(t, "--packages", pattern, "--types")
			if code != 0 || !reflect.DeepEqual(declarationFiles(r), []string{"component.go/source.go"}) {
				t.Fatalf("code=%d stderr=%s report=%+v", code, stderr, r)
			}
		})
	}
	r, code, stderr := runJSON(t, "--packages", "target_windows.go", "--types")
	if code != 2 || r.Summary.Files != 0 || !strings.Contains(stderr, "not Go file paths") {
		t.Fatalf("file argument bypassed build constraints: code=%d stderr=%s report=%+v", code, stderr, r)
	}
}

func TestPackageExclusionPrecedesErrors(t *testing.T) {
	setupPackageModule(t)
	writeFile(t, "base.go", "package fixture\ntype Base int")
	writeFile(t, "broken/first.go", "package first\ntype First int")
	writeFile(t, "broken/second.go", "package second\ntype Second int")
	for _, pattern := range []string{"broken", "broken/**"} {
		t.Run(pattern, func(t *testing.T) {
			r, code, stderr := runJSON(t, "--packages", "./...", "--exclude", pattern, "--types")
			if code != 0 || r.Status != "complete" || !reflect.DeepEqual(declarationFiles(r), []string{"base.go"}) ||
				r.Summary.SkippedReasons["excluded"] != 1 {
				t.Fatalf("code=%d stderr=%s report=%+v", code, stderr, r)
			}
		})
	}
}

